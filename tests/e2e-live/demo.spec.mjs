  await page.getByRole('button', { name: 'Thu hồi phiên' }).first().click();
  await expect(page.getByRole('button', { name: 'Thu hồi phiên' })).toHaveCount(1);
  await api('/api/v1/me', 'GET', undefined, otherSession, undefined, [401]);
